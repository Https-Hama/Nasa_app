import test from 'node:test';
import assert from 'node:assert/strict';
import { missionReviewHTML } from '../src/mission-review-ui.js';

const record = (overrides = {}) => ({ id: 'measured-mission', source: 'measured', conditions: { sessionStage: 'complete' }, ...overrides });
const review = (overrides = {}) => ({
  summary: 'You completed three memory rounds and eight focus cues.',
  strengths: ['The full memory sequence was completed.'],
  observations: ['One focus cue was missed.'],
  nextSteps: ['Try another session under the same conditions.'],
  limitations: ['The camera was not enabled.'],
  provider: 'Gemini', generatedAt: Date.parse('2026-11-15T09:00:00Z'),
  ...overrides,
});

test('a saved review shows the actual generated summary, sections, provider and date', () => {
  const html = missionReviewHTML({ record: record({ geminiReview: review() }) });
  for (const text of ['You completed three memory rounds', 'The full memory sequence', 'One focus cue was missed', 'Try another session', 'The camera was not enabled', 'Generated by Gemini', '15 Nov 2026']) assert.ok(html.includes(text), text);
  assert.match(html, /<time datetime="2026-11-15T09:00:00\.000Z"/);
  assert.match(html, /AI-generated interpretation/);
  assert.doesNotMatch(html, /data-mission-review-retry/);
});

test('pending generation has an accessible nonblocking status and decorative loading skeleton', () => {
  const html = missionReviewHTML({ record: record(), state: { status: 'pending' } });
  assert.match(html, /aria-busy="true"/);
  assert.match(html, /role="status" aria-live="polite"/);
  assert.match(html, /class="mission-review-skeleton" aria-hidden="true"/);
  assert.match(html, /local report remains available/);
  assert.doesNotMatch(html, /<dialog|data-mission-review-retry/);
});

test('an error is escaped and offers a report-specific accessible retry button', () => {
  const html = missionReviewHTML({ record: record({ id: 'report-" onclick="bad()' }), state: { status: 'error', error: '<img src=x onerror="bad()">' } });
  assert.match(html, /role="alert"/);
  assert.match(html, /&lt;img src=x onerror=&quot;bad\(\)&quot;&gt;/);
  assert.match(html, /data-mission-review-retry="report-&quot; onclick=&quot;bad\(\)"/);
  assert.match(html, />Retry Gemini review<\/button>/);
  assert.doesNotMatch(html, /<img|data-mission-review-retry="[^"]*"\s+onclick=/);
});

test('untrusted generated text is rendered as text in every review section', () => {
  const unsafe = '<img src=x onerror="bad()">';
  const html = missionReviewHTML({ record: record(), state: { status: 'ready', review: review({ summary: unsafe, strengths: [unsafe], observations: [unsafe], nextSteps: [unsafe], limitations: [unsafe] }) } });
  assert.equal((html.match(/&lt;img/g) || []).length, 5);
  assert.doesNotMatch(html, /<img|<script/);
});

test('disabled generation explains Preferences and offers no retry', () => {
  const html = missionReviewHTML({ record: record(), state: { status: 'disabled' } });
  assert.match(html, /Automatic review is off/);
  assert.match(html, /Preferences/);
  assert.match(html, /Names, video and check-in notes stay on this device/);
  assert.doesNotMatch(html, /data-mission-review-retry/);
});

test('turning off automatic generation does not hide an already saved review', () => {
  const html = missionReviewHTML({ record: record({ geminiReview: review() }), state: { status: 'disabled' } });
  assert.match(html, /You completed three memory rounds/);
  assert.doesNotMatch(html, /data-mission-review-retry/);
});

test('fictional previews do not imply an automatic API request or offer generation', () => {
  const html = missionReviewHTML({ record: record({ source: 'demo' }) });
  assert.match(html, /sample report is fictional/);
  assert.doesNotMatch(html, /sent to Gemini|data-mission-review-retry|aria-busy/);
});

for (const sessionStage of ['flight', 'mind']) {
  test(`saved ${sessionStage} progress explains completion before review`, () => {
    const html = missionReviewHTML({ record: record({ conditions: { sessionStage } }) });
    assert.match(html, /Finish your mission first/);
    assert.match(html, /Complete the flight and finish the mind check/);
    assert.doesNotMatch(html, /data-mission-review-retry|aria-busy/);
  });
}

test('an eligible report without review state explains automatic generation and what is sent', () => {
  const html = missionReviewHTML({ record: record() });
  assert.match(html, /generate automatically/);
  assert.match(html, /derived camera measurements, flight results and task scores are sent to Gemini/);
  assert.match(html, /data-mission-review-retry="measured-mission"/);
});

test('a ready state with malformed generated output offers retry instead of empty prose', () => {
  const html = missionReviewHTML({ record: record(), state: { status: 'ready', review: { summary: '' } } });
  assert.match(html, /saved review could not be opened/);
  assert.match(html, /data-mission-review-retry/);
});
